def esc(text: str) -> str:
    """Экранирует спецсимволы XML и заменяет апострофы/кавычки на типографские."""
    text = text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    text = text.replace("\"", "&#x201C;")  # упрощённо: левая ёлочка
    text = text.replace("'", "&#x2019;")
    return text


