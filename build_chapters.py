async def register_user(self, login: str, password: str, db):
    cursor = await db.execute("SELECT id FROM users WHERE login=?", (login,))
    if await cursor.fetchone():
        return None  # логин уже занят

    raw_token = secrets.token_hex(32)
    token_hash = hashlib.sha256(raw_token.encode()).hexdigest()
    password_hash = bcrypt.hashpw(password.encode(), bcrypt.gensalt()).decode()
    token_encrypted = encrypt_token(raw_token)  # Fernet (AES-128 + HMAC)

    await db.execute(
        "INSERT INTO users (login, password_hash, token_hash, token_encrypted) "
        "VALUES (?, ?, ?, ?)",
        (login, password_hash, token_hash, token_encrypted)
    )
    await db.commit()
    return raw_token
