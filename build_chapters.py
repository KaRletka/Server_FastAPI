# ── Вставка цитат с атрибуцией в теоретическую главу ──────────────────────────
def insert_after_paragraph(text_xml: str, anchor: str, paragraph_xml: str) -> str:
    """Вставляет paragraph_xml сразу после </w:p>, замыкающего абзац с anchor."""
    pos = text_xml.find(anchor)
    if pos == -1:
        raise SystemExit(f"Не найден якорь для цитаты: {anchor[:70]}…")
    close = text_xml.find("</w:p>", pos)
    if close == -1:
        raise SystemExit(f"Не найден </w:p> после якоря: {anchor[:70]}…")
    insert_at = close + len("</w:p>")
    return text_xml[:insert_at] + "\n" + paragraph_xml + text_xml[insert_at:]


