def build_table(rows, col_widths, caption_num, caption_title):
    out = []
    out.append(f'''<w:p>
      <w:pPr>
        <w:spacing w:before="240" w:line="360" w:lineRule="auto"/>
        <w:rPr><w:color w:val="000000" w:themeColor="text1"/></w:rPr>
      </w:pPr>
      <w:r>
        <w:rPr><w:color w:val="000000" w:themeColor="text1"/></w:rPr>
        <w:t>{esc(f"Таблица {caption_num}")}</w:t>
      </w:r>
    </w:p>''')
    out.append(f'''<w:p>
      <w:pPr>
        <w:spacing w:after="120" w:line="360" w:lineRule="auto"/>
        <w:rPr><w:color w:val="000000" w:themeColor="text1"/></w:rPr>
      </w:pPr>
      <w:r>
        <w:rPr><w:b/><w:bCs/><w:color w:val="000000" w:themeColor="text1"/></w:rPr>
        <w:t>{esc(caption_title)}</w:t>
      </w:r>
    </w:p>''')

    total = sum(col_widths)
    grid_cols = "".join(f'<w:gridCol w:w="{w}"/>' for w in col_widths)
    out.append(f'''<w:tbl>
      <w:tblPr>
        <w:tblW w:w="{total}" w:type="dxa"/>
        <w:tblBorders>
          <w:top w:val="single" w:sz="4" w:space="0" w:color="auto"/>
          <w:left w:val="single" w:sz="4" w:space="0" w:color="auto"/>
          <w:bottom w:val="single" w:sz="4" w:space="0" w:color="auto"/>
          <w:right w:val="single" w:sz="4" w:space="0" w:color="auto"/>
          <w:insideH w:val="single" w:sz="4" w:space="0" w:color="auto"/>
          <w:insideV w:val="single" w:sz="4" w:space="0" w:color="auto"/>
        </w:tblBorders>
        <w:tblLook w:val="04A0"/>
      </w:tblPr>
      <w:tblGrid>{grid_cols}</w:tblGrid>''')

    for i, row in enumerate(rows):
        is_header = (i == 0)
        out.append('<w:tr>')
        for j, cell in enumerate(row):
            shading = '<w:shd w:val="clear" w:color="auto" w:fill="DCE6F1"/>' if is_header else ''
            bold = '<w:b/><w:bCs/>' if is_header else ''
            out.append(f'''<w:tc>
              <w:tcPr>
                <w:tcW w:w="{col_widths[j]}" w:type="dxa"/>
                {shading}
                <w:tcMar>
                  <w:top w:w="80" w:type="dxa"/><w:left w:w="120" w:type="dxa"/>
                  <w:bottom w:w="80" w:type="dxa"/><w:right w:w="120" w:type="dxa"/>
                </w:tcMar>
              </w:tcPr>
              <w:p>
                <w:pPr><w:rPr><w:color w:val="000000" w:themeColor="text1"/></w:rPr></w:pPr>
                <w:r><w:rPr>{bold}<w:color w:val="000000" w:themeColor="text1"/><w:sz w:val="24"/><w:szCs w:val="24"/></w:rPr><w:t>{esc(cell)}</w:t></w:r>
              </w:p>
            </w:tc>''')
        out.append('</w:tr>')
    out.append('</w:tbl>')
    out.append('<w:p><w:pPr><w:spacing w:line="360" w:lineRule="auto"/></w:pPr></w:p>')
    return "".join(out)


def esc_code(text: str) -> str:
    """Экранирует XML-спецсимволы, НЕ трогая кавычки (в коде они должны остаться прямыми)."""
    return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


