def p_code(code: str) -> str:
    """Блок кода моноширинным шрифтом в рамке с серой заливкой."""
    code = code.strip("\n")
    lines = code.split("\n")
    runs = []
    rpr = ('<w:rPr><w:rFonts w:ascii="Courier New" w:hAnsi="Courier New" '
           'w:cs="Courier New"/><w:sz w:val="18"/><w:szCs w:val="18"/>'
           '<w:color w:val="000000" w:themeColor="text1"/></w:rPr>')
    for i, line in enumerate(lines):
        br = '<w:br/>' if i < len(lines) - 1 else ''
        runs.append(
            f'<w:r>{rpr}<w:t xml:space="preserve">{esc_code(line)}</w:t>{br}</w:r>'
        )
    return f'''<w:p>
      <w:pPr>
        <w:spacing w:after="160" w:line="240" w:lineRule="auto"/>
        <w:ind w:left="284"/>
        <w:jc w:val="left"/>
        <w:pBdr>
          <w:top w:val="single" w:sz="4" w:space="4" w:color="BFBFBF"/>
          <w:left w:val="single" w:sz="4" w:space="4" w:color="BFBFBF"/>
          <w:bottom w:val="single" w:sz="4" w:space="4" w:color="BFBFBF"/>
          <w:right w:val="single" w:sz="4" w:space="4" w:color="BFBFBF"/>
        </w:pBdr>
        <w:shd w:val="clear" w:color="auto" w:fill="F5F5F5"/>
        <w:rPr><w:rFonts w:ascii="Courier New" w:hAnsi="Courier New"/></w:rPr>
      </w:pPr>
      {"".join(runs)}
    </w:p>'''


